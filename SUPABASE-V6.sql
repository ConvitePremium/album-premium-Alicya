-- Execute no SQL Editor do projeto Supabase existente.
create table if not exists public.videos (
 id bigint generated by default as identity primary key,
 created_at timestamptz not null default now(),
 evento_id text not null,
 nome_convidado text not null,
 arquivo text not null unique
);
create index if not exists videos_evento_created_idx on public.videos(evento_id,created_at desc);
alter table public.videos enable row level security;
grant select,insert on public.videos to anon,authenticated;
create policy "videos leitura publica" on public.videos for select to anon,authenticated using (true);
create policy "videos envio convidados" on public.videos for insert to anon,authenticated with check (length(nome_convidado) between 1 and 50 and evento_id <> '' and arquivo like evento_id || '/videos/%');
